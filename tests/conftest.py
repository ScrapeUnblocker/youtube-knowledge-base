class FakeClient:
    """Answers youtube_channel / youtube_transcript from dictionaries and counts calls."""

    def __init__(self, channels=None, transcripts=None, missing=(), broken=()):
        self.channels = channels if channels is not None else {"@examplelab": CHANNEL}
        self.transcripts = transcripts if transcripts is not None else {}
        self.missing = set(missing)
        self.broken = set(broken)
        self.calls: list[tuple[str, str, dict[str, Any]]] = []

    def youtube_channel(self, channel: str, **kwargs: Any) -> Any:
        self.calls.append(("channel", channel, kwargs))
        if channel in self.broken:
            raise scrapeunblocker.ServerError("Blocked by YouTube", status_code=502)
        return copy.deepcopy(self.channels[channel])

    def youtube_transcript(self, video: str, **kwargs: Any) -> Any:
        self.calls.append(("transcript", video, kwargs))
        if video in self.broken:
            raise scrapeunblocker.ServerError("Blocked by YouTube", status_code=502)
        if video in self.missing or video not in self.transcripts:
            raise scrapeunblocker.NotFoundError("This video has no captions.", status_code=404)
        return copy.deepcopy(self.transcripts[video])


class Response:
    def __init__(self, status: int = 200, data: Any = None, text: str | None = None):
        self.status_code = status
        self._data = data
        self.text = text if text is not None else json.dumps(data if data is not None else {})
        self.headers: dict[str, str] = {}

    def json(self) -> Any:
        return self._data if self._data is not None else {}


class FakeHttp:
    """Records requests; ``routes`` maps (method, url substring) to a Response or a
    callable taking the request kwargs."""

    def __init__(self, routes=None):
        self.routes = routes or {}
        self.requests: list[dict[str, Any]] = []

    def request(self, method: str, url: str, **kwargs: Any) -> Response:
        self.requests.append({"method": method, "url": url, **kwargs})
        for (m, part), answer in self.routes.items():
            if m == method and part in url:
                return answer(kwargs) if callable(answer) else answer
        return Response(200, {"ok": True})

    def posts(self, part: str = "") -> list[Any]:
        return [r.get("json") for r in self.requests if r["method"] == "POST" and part in r["url"]]


